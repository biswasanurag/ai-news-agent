import html
import os
import smtplib
import ssl
from email.message import EmailMessage

import markdown
from dotenv import load_dotenv

load_dotenv()

HTML_TEMPLATE = """<!DOCTYPE html>
<html>
<body style="margin:0;padding:0;background:#f4f4f5;">
  <div style="max-width:640px;margin:0 auto;padding:24px;background:#ffffff;
              font-family:-apple-system,Segoe UI,Helvetica,Arial,sans-serif;
              font-size:16px;line-height:1.55;color:#1f2937;">
    {content}
    <hr style="border:none;border-top:1px solid #e5e7eb;margin:32px 0 12px;">
    <p style="font-size:12px;color:#6b7280;">Generated by your AI news agent.
    Summaries are written by an AI model from the linked sources. Check the
    originals before relying on them.</p>
  </div>
</body>
</html>"""

# Email clients ignore most stylesheets, so styles go inline on each tag.
INLINE_STYLES = {
    "<h1>": '<h1 style="font-size:24px;margin:0 0 16px;">',
    "<h2>": '<h2 style="font-size:18px;margin:28px 0 8px;color:#111827;'
            'border-bottom:1px solid #e5e7eb;padding-bottom:4px;">',
    "<li>": '<li style="margin-bottom:8px;">',
    "<a ": '<a style="color:#2563eb;" ',
}


def markdown_to_html(md_text: str) -> str:
    # Escape raw HTML first: the digest contains text derived from the web.
    safe = html.escape(md_text, quote=False)
    content = markdown.markdown(safe)
    for plain, styled in INLINE_STYLES.items():
        content = content.replace(plain, styled)
    return HTML_TEMPLATE.format(content=content)


def require_env(name: str) -> str:
    value = os.getenv(name)
    if not value:
        raise RuntimeError(f"Missing {name} in your .env file")
    return value


def send_digest(subject: str, markdown_body: str) -> None:
    sender = require_env("EMAIL_SENDER")
    password = require_env("EMAIL_APP_PASSWORD")
    recipient = os.getenv("EMAIL_RECIPIENT", sender)

    msg = EmailMessage()
    msg["Subject"] = subject
    msg["From"] = sender
    msg["To"] = recipient
    msg.set_content(markdown_body)  # plain-text fallback
    msg.add_alternative(markdown_to_html(markdown_body), subtype="html")

    context = ssl.create_default_context()
    with smtplib.SMTP_SSL("smtp.gmail.com", 465, context=context) as server:
        server.login(sender, password)
        server.send_message(msg)


